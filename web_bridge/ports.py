"""Host contracts. The bridge owns its protocol; the host owns accounts and workspaces."""
from contextlib import AbstractContextManager
from typing import Any, Protocol


class Principal(Protocol):
    user_id: str
    username: str


class IdentityTransaction(Protocol):
    def execute(self, sql: str, parameters=()) -> Any: ...
    def user(self, user_id: str) -> dict | None: ...
    def named_user(self, username: str) -> Principal: ...
    def create_user(self, user_id: str, username: str) -> None: ...
    def sync_username(self, user_id: str, username: str) -> None: ...
    def create_login(self, digest: str, user_id: str, expires: float) -> None: ...
    def revoke_login(self, digest: str) -> None: ...


class HostServices(Protocol):
    auth_error: type[Exception]
    access_denied: type[Exception]

    def current_user(self) -> Principal: ...
    def principal(self, user_id: str, username: str = '') -> Principal: ...
    def user_scope(self, user_id: str) -> AbstractContextManager: ...
    def identity_transaction(self) -> AbstractContextManager[IdentityTransaction]: ...
    def require_user(self, user_id: str) -> None: ...
    def ensure_session(self, session_id: str) -> dict: ...
    def require_session(self, session_id: str) -> None: ...
    def get_run(self, run_id: str) -> dict: ...
    def list_runs(self, session_id: str) -> list[dict]: ...
    def list_files(self, session_id: str) -> list[dict]: ...
    def resolve_transfer_files(self, session_id: str, paths: list[str]) -> list[dict]: ...
    def relative_file_path(self, path: str) -> str: ...
    def uploads(self) -> Any: ...
    def publish_text(self, session_id: str, filename: str, data: bytes, access=None) -> dict: ...
    def login_cookie(self, token: str) -> str: ...
    def serve_file(self, handler: Any, session_id: str, path: str) -> None: ...


_host: HostServices | None = None


def configure_host(host: HostServices | None) -> None:
    """Supply another agent's adapter, or reset to the bundled BioAgent adapter."""
    global _host
    _host = host


def get_host() -> HostServices:
    global _host
    if _host is None:
        # Lazy composition also works in independently spawned agent workers.
        from .adapters.bioagent import BioAgentHost
        _host = BioAgentHost()
    return _host
